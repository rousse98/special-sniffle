/*
|--------------------------------------------------------------------------
| DETECTAR IDIOMA DEL NAVEGADOR
|--------------------------------------------------------------------------
*/

$accept_language = $_SERVER['HTTP_ACCEPT_LANGUAGE'] ?? '';

$idioma_detectado = 'en';

/*
|--------------------------------------------------------------------------
| Analizar todos los idiomas enviados por el navegador
|--------------------------------------------------------------------------
|
| Ejemplo:
|
| es-ES,es;q=0.9,en-US;q=0.8,en;q=0.7
|
| Se intenta primero el idioma con mayor prioridad.
|
|--------------------------------------------------------------------------
*/

if (!empty($accept_language)) {

    $idiomas_navegador = explode(',', $accept_language);

    $preferencias = [];

    foreach ($idiomas_navegador as $posicion => $idioma_item) {

        $partes = explode(';q=', trim($idioma_item));

        $codigo = strtolower(trim($partes[0]));

        $calidad = isset($partes[1])
            ? (float) $partes[1]
            : 1.0;

        $codigo = str_replace('_', '-', $codigo);

        $preferencias[] = [
            'codigo' => $codigo,
            'calidad' => $calidad,
            'posicion' => $posicion
        ];
    }

    /*
    |--------------------------------------------------------------------------
    | Ordenar por prioridad q=
    |--------------------------------------------------------------------------
    */

    usort($preferencias, function ($a, $b) {

        if ($a['calidad'] == $b['calidad']) {
            return $a['posicion'] <=> $b['posicion'];
        }

        return $a['calidad'] < $b['calidad'] ? 1 : -1;
    });


    /*
    |--------------------------------------------------------------------------
    | Buscar coincidencia
    |--------------------------------------------------------------------------
    */

    foreach ($preferencias as $preferencia) {

        $codigo = $preferencia['codigo'];

        /*
        | Coincidencia exacta:
        | es-es
        | en-us
        | pt-br
        */

        if (isset($idiomas[$codigo])) {
            $idioma_detectado = $codigo;
            break;
        }


        /*
        | Coincidencia por idioma principal:
        | es-ES -> es
        | en-US -> en
        | pt-BR -> pt
        */

        $idioma_principal = substr($codigo, 0, 2);

        if (isset($idiomas[$idioma_principal])) {
            $idioma_detectado = $idioma_principal;
            break;
        }
    }
}


/*
|--------------------------------------------------------------------------
| SEGURIDAD
|--------------------------------------------------------------------------
